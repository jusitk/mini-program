'use strict';
/**
 * config.js —— 现场配置（老师可以直接用记事本改这个文件）
 *
 * 改完保存，关掉黑窗口重新双击「启动.bat」即可生效。
 * 也可以用环境变量覆盖这里的值（环境变量优先）：
 *   PORT / HOST / DATA_DIR / BACKUP_KEEP / BACKUP_EVERY_MIN / SEED_DEMO
 *
 * 注意：这个文件是纯文本，请用记事本另存为 **UTF-8** 编码。
 */

module.exports = {
  /** 服务端口。8080 被占用会自动往后顺延（启动横幅里会打印真实端口） */
  port: 8080,

  /** 监听地址。0.0.0.0 = 局域网里其它设备都能连（现场必须用这个）；127.0.0.1 = 只有本机能连 */
  host: '0.0.0.0',

  /** 数据目录（数据库、备份、上传的图片语音都在这里）。**整个目录复制走就是完整备份** */
  dataDir: '',          // 留空 = 程序目录下的 data

  /**
   * 自动备份：每隔多少分钟检查一次（有改动才真的备）。
   *
   * **默认 0 = 关掉自动备份**（现场要求：不要定时任务，也不要"每次打开都动备份"）。
   *   关掉之后备份只在两种时候产生：
   *     · 后台「备份与导出」里手动点「立即备份」
   *     · 启动时**确实有改动**才备一份（没改动就跳过，不动备份目录）
   *
   * ⚠ 代价：如果程序崩了或电脑断电，没有自动的兜底 —— 只能靠最后手动备的那份。
   *   现场赛前一小时建议在后台点一次「立即备份」。
   *   想恢复自动备份就把这里改成 30（分钟）。
   */
  backupEveryMin: 0,

  /**
   * 备份保留份数。
   *
   * **默认 0 = 永不自动删除**（现场要求：别每次打开都清备份）。
   * 备份只会因为你手点「删除」而消失。
   * ⚠ 一份约 1.4 MB；手动备份几百次也就几百 MB。真想限制就设成 30。
   */
  backupKeep: 0,

  /**
   * 后台维护任务（清过期登录、清幂等记录、合并 WAL、裁剪聊天记录）。
   *
   * 默认 `true`。这些**不动成绩数据、也不动备份**，只是防止数据库无限增长
   * （幂等表每录一条成绩就写一行，不清会一直涨）。
   * 想要"一个定时器都不建"就设成 `false`。
   */
  housekeeping: true,

  /** 单个聊天附件（图片/语音）大小上限，单位 MB */
  uploadMaxMB: 12,

  /** 启动时是否载入演示数据。现场正式比赛请保持 false */
  seedDemo: false,

  /**
   * 一个账号能不能同时在多台设备上登录。
   *
   * 默认 **false = 只能一台**（现场口径）：同一个账号在别处登录，
   * 原来那台会被**立刻顶下线**。
   *
   * 【为什么默认只让一台】共用账号是现场最容易被忽略的出错来源：
   * 两个人用同一个操作员账号、各自在自己手机上录成绩，
   * 一旦录到同一个项目就会互相覆盖（系统有乐观锁会拦一下，
   * 但两个人会不停看到"刚被别人改过"，越录越乱）。
   * 一人一台、各用各的账号，才是干净的用法。
   *
   * 被顶下线的那台不会"莫名其妙不能用了"：页面会弹出提示
   * 「这个账号在另一台设备上登录了，你已被下线」，并跳到登录页。
   *
   * 如果确实需要"电脑上开着、手机上也能登录同一个账号"，
   * 把这里改成 true。
   */
  allowMultiDeviceLogin: false,

  /** 首次启动的管理员账号名 */
  adminUser: 'admin',

  /**
   * 首次启动时给管理员设的口令。
   * 这里是**给学校用的简单口令**，好记好念；只在"这台机器上还没有任何账号"时用一次，
   * 之后在后台改过口令或跑过「重置口令.bat」都不会被它覆盖。
   *
   * 规则（改的时候注意）：至少 6 位、不能全是数字、不能是 123456 / password 这类常见串。
   * 想更安全就把它改复杂些，或者删成空字符串 '' 让程序随机生成一个
   * （随机的会打印在启动横幅里，同时写到项目目录下的「口令.txt」）。
   */
  adminPassword: 'admin123',
};
