/**
 * 检查一条网格轨道声明，返回问题列表。
 * 每条问题：{ 级别: '失败' | '可疑', 原因: string }
 *
 * 值文本必须是"已屏蔽注释/字符串"的版本，保证括号配对与上下文判断正确。
 */
function 检查轨道声明(属性名, 值文本) {
  const 问题 = [];

  // ---- 规则一：calc() 里出现「裸数字 × 无单位变量」=> 整条声明失效 ----
  for (const 调用 of 扫描函数调用(值文本, 'calc')) {
    const 体 = 调用.体;
    const 命中集 = new Set();

    // 数字 * var(...)   /   数字 / var(...)
    正则_数字乘变量.lastIndex = 0;
    let 匹配;
    while ((匹配 = 正则_数字乘变量.exec(体)) !== null) {
      const { 数字, 运算符, 变量, 回退 } = 匹配.groups;
      if (变量可能带单位(回退)) continue; // var(--x, 10px) 这类是合法的「数字 × 长度」
      const 描述 = `calc(${数字} ${运算符} ${变量})`;
      if (命中集.has(描述)) continue;
      命中集.add(描述);
      问题.push({
        级别: '失败',
        原因: `网格轨道里出现 ${描述}，会让整条声明失效`,
      });
    }

    // var(...) * 数字
    正则_变量乘数字.lastIndex = 0;
    while ((匹配 = 正则_变量乘数字.exec(体)) !== null) {
      const { 数字, 运算符, 变量, 回退 } = 匹配.groups;
      if (变量可能带单位(回退)) continue;
      const 描述 = `calc(${变量} ${运算符} ${数字})`;
      if (命中集.has(描述)) continue;
      命中集.add(描述);
      问题.push({
        级别: '失败',
        原因: `网格轨道里出现 ${描述}，会让整条声明失效`,
      });
    }
  }

  // ---- 规则二：repeat() 的参数里出现 calc() => 按项目约定禁止 ----
  for (const 调用 of 扫描函数调用(值文本, 'repeat')) {
    if (/calc\s*\(/i.test(调用.体)) {
      问题.push({
        级别: '失败',
        原因: 'repeat() 的参数里出现 calc()，按项目约定禁止（请把计算结果预先放进 CSS 变量）',
      });
    }
  }

  // ---- 规则三：minmax() 的怪组合 => 仅报可疑 ----
  for (const 调用 of 扫描函数调用(值文本, 'minmax')) {
    const 参数 = 拆参数(调用.体);
    if (参数.length !== 2) {
      问题.push({
        级别: '可疑',
        原因: `minmax() 需要恰好两个参数（最小值、最大值），这里检测到 ${参数.length} 个`,
      });
      continue;
    }
    const [最小, 最大] = 参数;

    if (正则_弹性单位.test(最小)) {
      问题.push({
        级别: '可疑',
        原因: 'minmax() 的最小值用了 fr 弹性单位，规范不允许（最大值才能是 fr）',
      });
    } else if (正则_百分比.test(最小) && 正则_固定长度.test(最大)) {
      问题.push({
        级别: '可疑',
        原因: 'minmax() 的最小值是百分比、最大值是固定长度：空间不足时最小值会超过最大值，通常不是本意',
      });
    } else if (正则_固定长度.test(最小) && 正则_百分比.test(最大)) {
      问题.push({
        级别: '可疑',
        原因: 'minmax() 的最小值是固定长度、最大值是百分比：空间不足时最小值会超过最大值，通常不是本意',
      });
    }
  }

  // ---- 规则四：auto-fit / auto-fill 出现在 repeat() 外面 => 仅报可疑 ----
  let 去掉repeat = 值文本;
  for (const 调用 of 扫描函数调用(值文本, 'repeat')) {
    // 把整个 repeat(...) 抹成空格（等长，方便定位）
    去掉repeat =
      去掉repeat.slice(0, 调用.起) +
      ' '.repeat(调用.止 - 调用.起 + 1) +
      去掉repeat.slice(调用.止 + 1);
  }
  if (/auto-(?:fit|fill)\b/i.test(去掉repeat)) {
    问题.push({
      级别: '可疑',
      原因: 'auto-fit / auto-fill 只能出现在 repeat() 里，写在外面会让整条声明失效',
    });
  }

  return 问题;
}

