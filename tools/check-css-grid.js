#!/usr/bin/env node
'use strict';

/* =============================================================================
 * check-css-grid.js —— CSS 网格轨道写法静态检查（零第三方依赖）
 *
 * 【这个工具防的是什么坑】
 *   本项目前端是原生 HTML/CSS（无构建、无框架）。历史上踩过一次很贵的坑：
 *   有人把 CSS 变量当成"纯数字"来用，写成了
 *       grid-template-columns: repeat(2, calc(320 * var(--s)));
 *   其中 --s 其实是一个不带单位的数字。CSS 的 calc() 允许「数字 × 长度」，
 *   但「数字 × 数字」得到的只是一个没有类型的纯数字，它无法充当网格轨道尺寸，
 *   于是【整条 grid-template-columns 声明在计算值阶段被判定为无效】——
 *   注意不是这一项失效，而是整条声明失效：网格直接塌成一列，
 *   表格、大屏卡片全部竖着堆起来。页面看起来"只是样式有点怪"，
 *   在浏览器里不会有任何报错，排查成本极高。同类坑还有：
 *     1) repeat() 的参数里塞 calc()：按项目约定一律禁止（各浏览器/旧版 Chrome
 *        对 repeat() 内 math function 的解析不一致，容易埋雷）；
 *     2) auto-fit / auto-fill 写到了 repeat() 外面：会被整条声明判为无效；
 *     3) minmax() 里第一个参数是百分比、第二个是固定长度这类"最小值可能大于
 *        最大值"的怪组合，结果通常不是作者本意（这一类只报「可疑」，不报错）。
 *
 * 【什么时候跑】
 *   - 本地改完 CSS / HTML 之后：node tools/check-css-grid.js
 *   - 提交前 / CI：npm run check:css（已被 npm run check 串进总检查）
 *   - 页面出现"网格塌成一列""卡片竖着排"的症状时，先跑它定位。
 *
 * 【用法】
 *   node tools/check-css-grid.js [--root=<项目根目录>]
 *   默认根目录 = 本脚本所在目录的上一级（即项目根目录）。
 *
 * 【扫描范围】
 *   <root>/public 下递归的所有 *.css / *.html / *.htm
 *   （HTML 里的 <style> 块也会被检查，行号按 HTML 文件真实行号报告）；
 *   若不存在 public 目录，则退化为扫描 <root> 自身（方便测试指向临时夹具目录）。
 *   块注释与字符串字面量里的内容一律不算（所以"注释里举例说明坏写法"不会误报）。
 *
 * 【输出】
 *   每处问题一行：[失败] 相对路径:行号  原因：属性: 值
 *   全部通过时：[通过] CSS 网格检查：共扫描 N 个文件，未发现会让网格塌陷的写法
 *
 * 【退出码】
 *   0 = 通过（可能附带「可疑」提示，「可疑」不影响退出码）
 *   1 = 发现会让网格轨道失效的写法，或参数/根目录不可用
 * ========================================================================== */

const fs = require('node:fs');
const path = require('node:path');

// ---------------------------------------------------------------------------
// 常量定义
// ---------------------------------------------------------------------------

/** 需要检查的网格轨道属性（值会影响轨道划分，坏了就塌）。 */
const 轨道属性表 = [
  'grid-template-columns',
  'grid-template-rows',
  'grid-template',
  'grid-auto-columns',
  'grid-auto-rows',
];

/** 匹配「轨道属性: 值」的开头；长属性名排在前面，避免被 grid-template 抢先匹配。 */
const 轨道属性正则 = new RegExp(
  String.raw`(?:^|[;{}])\s*(${轨道属性表.join('|')})\s*:`,
  'gi'
);

/** 不带单位的裸数字（前后都不能紧跟标识符/小数点/单位/百分号）。 */
const 裸数字源码 = String.raw`(?<![\w.\-#%])(?:\d+\.\d*|\.\d+|\d+)(?![\w.\-%])`;

/** var(--名) 或 var(--名, 回退值)，回退值允许一层嵌套括号（用具名分组，避免下标数错）。 */
const 变量源码 =
  String.raw`var\(\s*(?<变量名>--[\w-]+)\s*(?:,\s*(?<回退>[^()]*(?:\([^()]*\)[^()]*)*))?\)`;

/** calc(裸数字 * var(...)) / calc(裸数字 / var(...)) —— 必然无效。 */
const 正则_数字乘变量 = new RegExp(
  String.raw`(?<数字>${裸数字源码})\s*(?<运算符>[*/])\s*(?<变量>${变量源码})`,
  'gi'
);

/** calc(var(...) * 裸数字) —— 乘法可交换，同样是「数字 × 数字」风险。 */
const 正则_变量乘数字 = new RegExp(
  String.raw`(?<变量>${变量源码})\s*(?<运算符>\*)\s*(?<数字>${裸数字源码})`,
  'gi'
);

/** 带单位的长度字面量（用于 minmax 的"固定长度"判断）。 */
const 正则_固定长度 =
  /^-?\d*\.?\d+(px|rem|em|ex|ch|cap|ic|lh|rlh|vw|vh|vmin|vmax|cm|mm|q|in|pt|pc)$/i;

/** 百分比字面量。 */
const 正则_百分比 = /^\d*\.?\d+%$/;

/** 弹性单位 fr。 */
const 正则_弹性单位 = /^\d*\.?\d+fr$/i;

/** 递归扫描时要跳过的目录。 */
const 跳过目录 = new Set(['node_modules', '.git', '.svn', '.hg', 'dist', 'build']);

