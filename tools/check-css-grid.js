// 扫描单元：普通 CSS 文件 / HTML 里的 <style> 块
// ---------------------------------------------------------------------------

/**
 * 从一个文件里切出所有"待检查单元"。
 * 每个单元：{ 原始文本, 起始行 }（起始行是这段文本第一行在文件中的真实行号）
 */
function 切分扫描单元(文件路径, 源文本) {
  const 扩展名 = path.extname(文件路径).toLowerCase();

  if (扩展名 === '.css') {
    return [{ 原始文本: 源文本, 起始行: 1 }];
  }

  // HTML：只取 <style> 块里的内容，行号换算成 HTML 文件的真实行号
  const 单元列表 = [];
  const 正则 = /<style\b[^>]*>([\s\S]*?)<\/style\s*>/gi;
  let 匹配;
  while ((匹配 = 正则.exec(源文本)) !== null) {
    const 内容 = 匹配[1];
    if (内容.trim() === '') continue;
    const 内容起点 = 匹配.index + 匹配[0].indexOf('>') + 1;
    const 前面 = 源文本.slice(0, 内容起点);
    const 起始行 = 前面.split('\n').length; // 内容第一行所在的行号
    单元列表.push({ 原始文本: 内容, 起始行 });
  }
  return 单元列表;
}

/**
 * 扫描一个单元，返回问题列表（带文件内的真实行号）。
 */
function 扫描单元(单元) {
  const 屏蔽后 = 屏蔽注释与字符串(单元.原始文本);
  const 问题列表 = [];

  轨道属性正则.lastIndex = 0;
  let 匹配;
  while ((匹配 = 轨道属性正则.exec(屏蔽后)) !== null) {
    const 属性名 = 匹配[1].toLowerCase();
    const 值起点 = 匹配.index + 匹配[0].length;

    // 顺着找这条声明的结尾：括号深度为 0 时的 ';' 或 '}'
    let i = 值起点;
    let 深度 = 0;
    while (i < 屏蔽后.length) {
      const 字符 = 屏蔽后[i];
      if (字符 === '(') 深度++;
      else if (字符 === ')') 深度 = Math.max(0, 深度 - 1);
      else if (深度 === 0 && (字符 === ';' || 字符 === '}')) break;
      i++;
    }

    const 值文本 = 屏蔽后.slice(值起点, i).trim();
    if (值文本 === '') continue;

    // 行号：单元内换行数 + 单元起始行
    const 行号 = 单元.起始行 + 单元.原始文本.slice(0, 值起点).split('\n').length - 1;

    // 报告里用的是"原汁原味"的文本（注释/字符串位置在原文里）
    const 原值 = 单元.原始文本.slice(值起点, i).trim();

    for (const 问题 of 检查轨道声明(属性名, 值文本)) {
      问题列表.push({
        级别: 问题.级别,
        行号,
        属性名,
        值: 原值,
        原因: 问题.原因,
      });
    }
  }

  return 问题列表;
}

// ---------------------------------------------------------------------------
// 命令行参数
// ---------------------------------------------------------------------------

const 用法 = `用法：node tools/check-css-grid.js [--root=<项目根目录>]

  --root=<目录>   指定项目根目录（默认取本脚本所在目录的上一级）
  -h, --help      显示这段帮助

说明：默认扫描 <root>/public 下的 *.css 与 *.html（含 <style> 块）；
      若没有 public 目录，则扫描 <root> 自身（方便用临时夹具目录做测试）。
退出码：0 = 通过；1 = 发现问题或目录/参数不可用。`;

function 解析参数(参数表) {
  const 选项 = {
    根目录: path.resolve(__dirname, '..'),
    帮助: false,
    未知参数: [],
    错误: '',
  };

  for (let i = 0; i < 参数表.length; i++) {
    const 参数 = 参数表[i];
    if (参数 === '--help' || 参数 === '-h') {
      选项.帮助 = true;
    } else if (参数.startsWith('--root=')) {
      const 值 = 去引号(参数.slice('--root='.length)).trim();
      if (值 === '') 选项.错误 = '--root 后面没有给出目录';
      else 选项.根目录 = path.resolve(值);
    } else if (参数 === '--root' || 参数 === '-r') {
      const 值 = 参数表[i + 1];
      if (值 === undefined) {
        选项.错误 = '--root 后面没有给出目录';
      } else {
        选项.根目录 = path.resolve(去引号(值).trim());
        i++;
      }
    } else {
      选项.未知参数.push(参数);
    }
  }

  return 选项;
}

// ---------------------------------------------------------------------------
// 主流程
// ---------------------------------------------------------------------------

function 主函数() {
  const 选项 = 解析参数(process.argv.slice(2));

  if (选项.帮助) {
    console.log(用法);
    return 0;
  }

  for (const 未知 of 选项.未知参数) {
    console.log(`[提示] 忽略了无法识别的参数：${未知}`);
  }

  if (选项.错误) {
    console.error(`[失败] 参数错误：${选项.错误}`);
    console.error(用法);
    return 1;
  }

  let 是目录 = false;
  try {
    是目录 = fs.statSync(选项.根目录).isDirectory();
  } catch {
    是目录 = false;
  }
  if (!是目录) {
    console.error(`[失败] 根目录不存在或不是目录：${选项.根目录}`);
    return 1;
  }

  const { 文件列表, 用了public, 起点 } = 收集待检查文件(选项.根目录);
  if (!用了public) {
    console.log(`[提示] 未找到 public 目录，改为扫描：${起点}`);
  }
  if (文件列表.length === 0) {
    console.log(`[提示] 扫描目录下没有任何 .css / .html 文件：${起点}`);
  }

  const 失败列表 = [];
  const 可疑列表 = [];
  const 已见 = new Set();
  let 已扫描文件数 = 0;

  for (const 文件路径 of 文件列表) {
    let 源文本;
    try {
      源文本 = fs.readFileSync(文件路径, 'utf8');
    } catch (错误) {
      console.error(`[失败] 读取文件失败：${文件路径}（${错误.message}）`);
      失败列表.push({
        相对路径: path.relative(选项.根目录, 文件路径).split(path.sep).join('/'),
        行号: 1,
        级别: '失败',
        原因: `文件无法读取：${错误.message}`,
        属性名: '',
        值: '',
      });
      continue;
    }

    // 统一换行符，保证行号统计一致（\r\n 里的 \r 不算换行）
    const 规范化 = 源文本.replace(/\r\n?/g, '\n');
    已扫描文件数++;

    const 相对路径 = path.relative(选项.根目录, 文件路径).split(path.sep).join('/');

    for (const 单元 of 切分扫描单元(文件路径, 规范化)) {
      for (const 问题 of 扫描单元(单元)) {
        const 记录 = {
          相对路径,
          行号: 问题.行号,
          级别: 问题.级别,
          原因: 问题.原因,
          属性名: 问题.属性名,
          值: 问题.值,
        };
        const 指纹 = [
          记录.相对路径,
          记录.行号,
          记录.级别,
          记录.原因,
          记录.属性名,
          记录.值,
        ].join('\u0000');
        if (已见.has(指纹)) continue;
        已见.add(指纹);
        (记录.级别 === '失败' ? 失败列表 : 可疑列表).push(记录);
      }
    }
  }

  const 排序 = (甲, 乙) =>
    甲.相对路径.localeCompare(乙.相对路径) || 甲.行号 - 乙.行号;
  失败列表.sort(排序);
  可疑列表.sort(排序);

  for (const 记录 of 失败列表) {
    console.log(
      `[失败] ${记录.相对路径}:${记录.行号}  ${记录.原因}：` +
        `${记录.属性名}: ${压平(记录.值)}`
    );
  }
  for (const 记录 of 可疑列表) {
    console.log(
      `[可疑] ${记录.相对路径}:${记录.行号}  ${记录.原因}：` +
        `${记录.属性名}: ${压平(记录.值)}`
    );
  }

  if (失败列表.length === 0) {
    if (可疑列表.length > 0) {
      console.log(
        `[提示] 另有 ${可疑列表.length} 处可疑写法（不影响退出码，建议人工确认）`
      );
    }
    console.log(
      `[通过] CSS 网格检查：共扫描 ${已扫描文件数} 个文件，未发现会让网格塌陷的写法`
    );
    return 0;
  }

  console.log(
    `[结果] CSS 网格检查：共扫描 ${已扫描文件数} 个文件，` +
      `发现 ${失败列表.length} 处会让网格轨道失效的写法（另有 ${可疑列表.length} 处可疑）`
  );
  return 1;
}

process.exitCode = 主函数();
