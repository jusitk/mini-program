/** 递归收集目录下需要检查的文件（绝对路径）。 */
function 收集文件(目录, 结果) {
  let 条目;
  try {
    条目 = fs.readdirSync(目录, { withFileTypes: true });
  } catch {
    return 结果; // 目录不可读就跳过，不让工具本身崩掉
  }
  条目.sort((甲, 乙) => (甲.name < 乙.name ? -1 : 甲.name > 乙.name ? 1 : 0));

  for (const 项 of 条目) {
    const 全路径 = path.join(目录, 项.name);
    if (项.isDirectory()) {
      if (跳过目录.has(项.name)) continue;
      收集文件(全路径, 结果);
      continue;
    }
    if (!项.isFile()) continue;
    const 扩展名 = path.extname(项.name).toLowerCase();
    if (扩展名 === '.css' || 扩展名 === '.html' || 扩展名 === '.htm') {
      结果.push(全路径);
    }
  }
  return 结果;
}

/**
 * 决定扫描哪些文件。
 * 优先 <root>/public（项目的静态资源目录）；没有就退化为扫描 <root> 自身，
 * 这样测试里可以把 --root 指向一个临时夹具目录。
 */
function 收集待检查文件(根目录) {
  const public目录 = path.join(根目录, 'public');
  let 起点 = 根目录;
  let 用了public = false;

  try {
    if (fs.statSync(public目录).isDirectory()) {
      起点 = public目录;
      用了public = true;
    }
  } catch {
    // 没有 public 目录，走退化路径
  }

  const 文件列表 = 收集文件(起点, []).sort();
  return { 文件列表, 用了public, 起点 };
}

