// 通用小工具
// ---------------------------------------------------------------------------

/** 去掉首尾成对的引号（Windows 命令行里 --root="F:\x" 会带引号）。 */
function 去引号(文本) {
  const 值 = String(文本);
  if (值.length >= 2) {
    const 头 = 值[0];
    const 尾 = 值[值.length - 1];
    if ((头 === '"' && 尾 === '"') || (头 === "'" && 尾 === "'")) {
      return 值.slice(1, -1);
    }
  }
  return 值;
}

/** 把连续空白压成一个空格并截断，便于单行输出。 */
function 压平(文本, 上限 = 200) {
  const 结果 = String(文本).replace(/\s+/g, ' ').trim();
  return 结果.length > 上限 ? 结果.slice(0, 上限) + '…' : 结果;
}

/**
 * 找配对括号：给定 '(' 的下标，返回对应 ')' 的下标；找不到返回 -1。
 * 输入必须是已经屏蔽掉注释和字符串的文本，否则引号里的括号会算错。
 */
function 找配对括号(文本, 左括号下标) {
  let 深度 = 0;
  for (let i = 左括号下标; i < 文本.length; i++) {
    const 字符 = 文本[i];
    if (字符 === '(') 深度++;
    else if (字符 === ')') {
      深度--;
      if (深度 === 0) return i;
    }
  }
  return -1;
}

/**
 * 在文本中找出所有 `函数名(` 调用，返回 { 起, 止, 体 } 列表。
 * 括号不配对时以文本结尾收尾，保证不丢内容。
 */
function 扫描函数调用(文本, 函数名) {
  const 结果 = [];
  const 正则 = new RegExp(函数名 + String.raw`\s*\(`, 'gi');
  let 匹配;
  while ((匹配 = 正则.exec(文本)) !== null) {
    const 左括号 = 匹配.index + 匹配[0].length - 1;
    const 右括号 = 找配对括号(文本, 左括号);
    if (右括号 === -1) {
      结果.push({ 起: 左括号, 止: 文本.length, 体: 文本.slice(左括号 + 1) });
      break;
    }
    结果.push({ 起: 左括号, 止: 右括号, 体: 文本.slice(左括号 + 1, 右括号) });
    正则.lastIndex = 左括号 + 1; // 继续向内扫描嵌套调用
  }
  return 结果;
}

/** 按顶层逗号拆分函数参数（忽略括号内的逗号）。 */
function 拆参数(文本) {
  const 结果 = [];
  let 深度 = 0;
  let 当前 = '';
  for (const 字符 of 文本) {
    if (字符 === '(') 深度++;
    else if (字符 === ')') 深度 = Math.max(0, 深度 - 1);
    if (字符 === ',' && 深度 === 0) {
      结果.push(当前);
      当前 = '';
      continue;
    }
    当前 += 字符;
  }
  结果.push(当前);
  return 结果.map((项) => 项.trim());
}

/**
 * 屏蔽注释与字符串：把内容替换成等长空格（换行保留）。
 * 这样既能"注释里的内容不算"，又能让所有下标/行号与原文件完全对齐。
 */
function 屏蔽注释与字符串(源文本) {
  const 输出 = 源文本.split('');
  const 长度 = 源文本.length;
  // 状态机：code（普通代码）/ comment（块注释）/ string（字符串字面量）
  let 状态 = 'code';
  let 引号 = '';
  let i = 0;

  // 顺手把 BOM 也当成空白，避免文件首个属性匹配不上
  if (长度 > 0 && 源文本.charCodeAt(0) === 0xfeff) 输出[0] = ' ';

  while (i < 长度) {
    const 字符 = 源文本[i];
    const 下一个 = 源文本[i + 1];

    if (状态 === 'code') {
      if (字符 === '/' && 下一个 === '*') {
        输出[i] = ' ';
        输出[i + 1] = ' ';
        状态 = 'comment';
        i += 2;
        continue;
      }
      if (字符 === '"' || 字符 === "'") {
        输出[i] = ' ';
        引号 = 字符;
        状态 = 'string';
        i += 1;
        continue;
      }
      i += 1;
      continue;
    }

    if (状态 === 'comment') {
      if (字符 === '*' && 下一个 === '/') {
        输出[i] = ' ';
        输出[i + 1] = ' ';
        状态 = 'code';
        i += 2;
        continue;
      }
      if (字符 !== '\n' && 字符 !== '\r') 输出[i] = ' ';
      i += 1;
      continue;
    }

    // 状态 === 'string'
    if (字符 === '\\') {
      输出[i] = ' ';
      if (i + 1 < 长度 && 源文本[i + 1] !== '\n' && 源文本[i + 1] !== '\r') {
        输出[i + 1] = ' ';
      }
      i += 2;
      continue;
    }
    if (字符 === 引号) {
      输出[i] = ' ';
      状态 = 'code';
      i += 1;
      continue;
    }
    if (字符 !== '\n' && 字符 !== '\r') 输出[i] = ' ';
    i += 1;
  }

  return 输出.join('');
}

/**
 * 判断一个 var() 是否"可能带单位"。
 * 没有回退值 → 无法确定，按无单位处理（这正是历史上出事的那种写法）。
 * 回退值是纯数字 → 确定无单位。
 * 回退值带单位 / 百分号 / 是函数 → 认为它是长度，不误报。
 */
function 变量可能带单位(回退值) {
  if (回退值 === undefined || 回退值 === null) return false;
  const 文本 = String(回退值).trim();
  if (文本 === '') return false;
  if (/^[+-]?(?:\d+\.\d*|\.\d+|\d+)$/.test(文本)) return false; // 纯数字
  return true; // 带单位、百分号或 calc()/var() 等，按"可能是长度"放过
}

